def generate_workflow_summary(
    metadata: Dict[str, Any],
    tracer=None
) -> str:
    """
    Generate a concise workflow summary for logging or quick reference.

    Args:
        metadata: Workflow metadata
        tracer: Optional tracer for additional stats

    Returns:
        Formatted summary string
    """
    duration = metadata.get("workflow_duration", 0)
    tokens = metadata.get("total_tokens", 0)
    layers = metadata.get("num_layers", 0)

    summary = f"""Single Agent Workflow Summary:
- Duration: {duration:.2f}s
- Layers: {layers}
- Tokens: ~{tokens}
- Self-Review: {metadata.get('self_review_enabled', False)}
- Models: {len(metadata.get('agents_used', {}))} cognitive functions
"""

    if tracer:
        stats = tracer.get_summary_stats()
        summary += f"- API Calls: {stats.get('total_api_calls', 0)}\n"
        summary += f"- Dissent Points: {stats.get('dissent_points_count', 0)}\n"
        summary += f"- Errors: {stats.get('error_count', 0)}\n"

    return summary