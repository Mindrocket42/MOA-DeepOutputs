"""
Report generation for Single Agent Workflow.

Generates comprehensive reports showing the cognitive workflow,
dissent management, confidence tracking, and performance metrics.
"""

from typing import List, Dict, Any
from datetime import datetime

from .utils import sanitize_for_markdown, format_timestamp_for_filename as format_timestamp
from .workflow import SingleAgentWorkflow

def generate_markdown_report(
    prompt: str,
    layer_outputs: List[Dict[str, Any]],
    final_output: str,
    metadata: Dict[str, Any],
    workflow: SingleAgentWorkflow
) -> str:
    """
    Generate a comprehensive markdown report for the single agent workflow.

    Args:
        prompt: Original user prompt
        layer_outputs: List of layer processing outputs
        final_output: Final agent response
        metadata: Workflow metadata
        workflow: SingleAgentWorkflow instance

    Returns:
        Formatted markdown report
    """
    timestamp = format_timestamp()
    num_layers = metadata.get("num_layers", 0)
    workflow_duration = metadata.get("workflow_duration", 0)
    total_tokens = metadata.get("total_tokens", 0)
    agents_used = metadata.get("agents_used", {})

    # Truncate original prompt for header
    truncated_prompt = prompt[:150] + "..." if len(prompt) > 150 else prompt

    markdown_content = f"""# Single Agent Workflow Response Report
**Generated:** {timestamp}

## System Configuration
- **Workflow Type:** Single Agent with Specialized Cognitive Functions
- **Layers Processed:** {num_layers}
- **Self-Review Enabled:** {metadata.get('self_review_enabled', False)}
- **Total Duration:** {workflow_duration:.2f}s
- **Total Tokens:** ~{total_tokens}

## Cognitive Function Models
- **Response Agent:** {agents_used.get('response', 'N/A')}
- **Devils Advocate:** {agents_used.get('devils_advocate', 'N/A')}
- **Synthesis Agent:** {agents_used.get('synthesis', 'N/A')}
- **Final Agent:** {agents_used.get('final', 'N/A')}

## Original Prompt
```
{prompt}
```

## Layer-by-Layer Analysis

"""

    # Add layer details
    for layer in layer_outputs:
        layer_num = layer.get("layer_number", 0)
        markdown_content += f"""### Layer {layer_num}

#### Response Agent
{sanitize_for_markdown(layer.get("response", "No response available"))}

"""

        if "self_review" in layer and layer["self_review"]:
            markdown_content += f"""#### Self-Review Assessment
{sanitize_for_markdown(layer.get("self_review", ""))}

"""

        if "devils_advocate" in layer:
            markdown_content += f"""#### Devils Advocate Critique
{sanitize_for_markdown(layer.get("devils_advocate", ""))}

"""

        if "synthesis" in layer:
            markdown_content += f"""#### Synthesis & Integration
{sanitize_for_markdown(layer.get("synthesis", ""))}

"""

    # Add final output
    markdown_content += f"""## Final Authoritative Answer

{sanitize_for_markdown(final_output)}

---
*Report generated by Single Agent Workflow Engine*
"""

    return markdown_content

